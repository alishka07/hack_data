def attach_episode_steps(report):
    """Return a copy; add event.steps and method descriptions to coverage rows."""
    result = deepcopy(report)
    result['explanation_version'] = VERSION
    for event in result.get('events', []):
        event['steps'] = build_event_steps(event)
    for row in result.get('rule_coverage', result.get('coverage', [])):
        planned = row.get('implementation_status') == 'not_implemented' or row.get('assessment_status') == 'not_implemented'
        status = 'planned' if planned else 'insufficient_evidence' if row.get('status') == 'not_checked' else 'method'
        row['procedure_status'] = status
        row['procedure_note'] = ('План проверки; автоматический метод ещё не реализован.' if planned else
                                 'Описание метода. На этой записи не хватает данных для его применения.' if status == 'insufficient_evidence' else
                                 'Порядок проверки, а не перечень доказанных действий человека.')
        definition = PROCEDURES.get(row.get('rule_id'), [('Проверить доступные наблюдения', row.get('detail', 'Данных о методе пока нет.'))])
        row['procedure_steps'] = [{'number': index, 'title': title, 'detail': detail, 'kind': 'procedure', 'status': status}
                                  for index, (title, detail) in enumerate(definition, 1)]
    return result
