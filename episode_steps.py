def _number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value) and value >= 0


def _step(title, detail, kind='observation', evidence=None, timestamp=None):
    result = {'title': title, 'detail': detail, 'kind': kind}
    if isinstance(evidence, dict):
        result['timestamp_sec'] = evidence['timestamp_sec']
        # Retain the actual frame reference, not a synthetic timestamp/frame.
        result['evidence'] = deepcopy(evidence)
    elif _number(timestamp):
        result['timestamp_sec'] = timestamp
    return result


def _evidence(event, labels=None):
    result = []
    seen = set()
    for item in event.get('evidence_times', []):
        if not isinstance(item, dict) or not _number(item.get('timestamp_sec')):
            continue
        if labels is not None and not labels.intersection(item.get('labels', [])):
            continue
        key = (item['timestamp_sec'], item.get('source_frame'), tuple(item.get('labels', [])))
        if key not in seen:
            result.append(item)
            seen.add(key)
    return sorted(result, key=lambda row: row['timestamp_sec'])


def _generic_observations(event, evidence):
    if not evidence:
        return [_step('Описание эпизода', event.get('description') or 'Нет кадров для пошагового восстановления.', 'limitation')]
    names = ', '.join(dict.fromkeys(LABELS.get(label, 'предмет') for label in evidence[0].get('labels', [])))
    result = [_step('Первое сохранённое наблюдение', f'В кадре отмечены: {names or "кандидаты объектов"}.', evidence=evidence[0])]
    if evidence[-1]['timestamp_sec'] > evidence[0]['timestamp_sec']:
        result.append(_step('Последнее сохранённое наблюдение',
                            'Это последняя опорная отметка данного эпизода; по двум крайним кадрам нельзя восстановить все промежуточные действия.',
                            evidence=evidence[-1]))
    return result


def build_event_steps(event):
    """Return observations, rule comparison and a limit for an existing event."""
    key = event.get('rule_id')
    context = event.get('context') if isinstance(event.get('context'), dict) else {}
    evidence = _evidence(event)
    steps = []
    limitation = None

    if key == 'door_open':
        rows = _evidence(event, {'door'})
        if rows and context.get('duration_basis') == 'observed_sample_span':
            span = rows[-1]['timestamp_sec'] - rows[0]['timestamp_sec']
            steps = [_step('Начало видимого открытия', 'Дверь распознана открытой в подтверждённом ракурсе.', evidence=rows[0])]
            if span > 0:
                steps.append(_step('Последнее открытое состояние', 'В проверенной последовательности открытие продолжается до этого кадра; неизвестное состояние разрывает интервал.', evidence=rows[-1]))
            reached = span + 1e-9 >= DOOR_OPEN_THRESHOLD_SEC
            steps.append(_step('Сравнение с порогом',
                               f'Наблюдаемый интервал {span:.2f} с. Порог пользователя — {DOOR_OPEN_THRESHOLD_LABEL}; '
                               + ('порог достигнут.' if reached else 'порог не достигнут.'), 'rule'))
        limitation = 'Это порог пользователя. Закрытая дверца не доказывает запирание; короткие изменения между проверенными кадрами могли быть пропущены.'

    elif key in {'cash_after_client', 'previous_client_documents'}:
        cash = key == 'cash_after_client'
        rows = _evidence(event, CASH_LABELS if cash else DOCUMENT_LABELS)
        exit_sec = context.get('visitor_exit_sec')
        before = [row for row in rows if _number(exit_sec) and row['timestamp_sec'] <= exit_sec]
        after = [row for row in rows if _number(exit_sec) and row['timestamp_sec'] > exit_sec]
        observation = 'Предполагаемые банкноты наблюдаются' if cash else 'Предполагаемый документ наблюдается'
        if before and after and context.get('same_projected_location') is True:
            steps.append(_step('Предмет до ухода посетителя', f'{observation} в проекции стола.', evidence=before[0]))
            departure_evidence = next((row for row in evidence if abs(row['timestamp_sec'] - exit_sec) < 1e-6 and 'person' in row.get('labels', [])), None)
            steps.append(_step('Посетитель уходит из видимой зоны',
                               'Траектория посетителя достигает края кадра и перестаёт наблюдаться. Роль определена по положению; это не подтверждение завершения операции.',
                               evidence=departure_evidence, timestamp=exit_sec))
            steps.append(_step('Предмет остаётся после ухода', f'{observation} повторно на прежнем месте в проекции стола.', evidence=after[-1]))
            steps.append(_step('Почему выделен эпизод',
                               'Правило касается денег, оставшихся после ухода клиента; само наличие денег при обслуживании нарушением не считается.' if cash else
                               'После видимого ухода посетителя документ остаётся на столе; его принадлежность требует проверки.', 'rule'))
        else:
            steps = _generic_observations(event, rows or evidence)
            steps.append(_step('Уход не восстановлен по этим данным',
                               'Недостаточно связанной последовательности: предмет до ухода → наблюдаемый уход → тот же предмет после. Один кассир в кадре и деньги на столе не доказывают, что клиент уже ушёл.', 'limitation'))
        limitation = 'Небольшой предмет может быть распознан ошибочно. Выход из кадра не равен выходу из помещения; завершение операции и принадлежность предмета неизвестны.'

    elif key == 'unattended_assets' and context.get('recording_ends_during_absence') is True:
        rows = _evidence(event, CASH_LABELS)
        absence = context.get('absence') if isinstance(context.get('absence'), dict) else {}
        start = absence.get('start_sec')
        before = [row for row in rows if _number(start) and row['timestamp_sec'] < start]
        after = [row for row in rows if _number(start) and row['timestamp_sec'] >= start]
        cashier = [row for row in evidence if 'person' in row.get('labels', [])
                   and _number(start) and row['timestamp_sec'] < start]

        def cash_origin(row):
            if row.get('source') == 'human_confirmed_reference_match':
                return 'На кадре найдено совпадение с образцом денег из этой же записи, класс которого уточнён пользователем; это сопоставление изображений, а не новое подтверждение человеком.'
            if row.get('source') == 'model':
                return 'Класс банкнот предложен моделью и требует просмотра.'
            return 'Источник классификации этого кадра не указан; ручное подтверждение не предполагается.'

        if before and after:
            steps.append(_step('Предмет до последнего видимого кассира',
                               f'Предмет отмечен в проекции стола. {cash_origin(before[0])}', evidence=before[0]))
            if cashier:
                steps.append(_step('Последнее наблюдение кассира',
                                   'Это последний сохранённый кадр позиционной траектории кассира. Выход из помещения или уход клиента этим не установлен.',
                                   evidence=cashier[-1]))
            steps.append(_step('Деньги при отсутствии видимых людей',
                               f'После этой траектории трекер не отмечает людей; предмет повторно виден на прежнем месте. {cash_origin(after[0])}',
                               evidence=after[0]))
            if after[-1]['timestamp_sec'] > after[0]['timestamp_sec']:
                steps.append(_step('Последнее сохранённое наблюдение денег',
                                   f'Предмет остаётся в проекции стола до последнего опорного кадра. {cash_origin(after[-1])}', evidence=after[-1]))
            steps.append(_step('Почему выделен короткий эпизод',
                               'Запись заканчивается во время отсутствия траекторий. Короткий конец записи выделен для проверки денег без видимого кассира; одна секунда — фильтр наблюдений, а не разрешённое время оставления денег.', 'rule'))
        else:
            steps = _generic_observations(event, rows or evidence)
        limitation = ('Не установлен выход кассира или клиента из помещения. Детектор мог пропустить перекрытого человека; '
                      'фактический присмотр вне кадра и события после конца записи неизвестны.')

    elif key == 'food_drinks_at_workplace':
        rows = _evidence(event, {'food', 'drink'})
        if rows:
            def origin(row):
                if row.get('source') == 'human_confirmed_reference_match':
                    return 'На этом кадре найдено совпадение с образцом из этой же записи, класс которого уточнён пользователем. Это сопоставление изображений, а не новое подтверждение человеком.'
                if row.get('source') == 'model':
                    return 'На этом кадре класс предложен моделью и требует просмотра; совпадение с уточнённым образцом не подтверждено.'
                return 'Источник классификации этого кадра не указан; совпадение с уточнённым образцом не подтверждено.'
            names = ', '.join(dict.fromkeys(LABELS[label] for label in rows[0].get('labels', []) if label in {'food', 'drink'}))
            steps.append(_step('Предмет у рабочего места', f'Отмечены: {names}. {origin(rows[0])}', evidence=rows[0]))
            if rows[-1]['timestamp_sec'] > rows[0]['timestamp_sec']:
                steps.append(_step('Повторные наблюдения', f'Предмет повторно обнаруживается у рабочего стола. {origin(rows[-1])} Содержимое чашки не распознаётся.', evidence=rows[-1]))
            if context.get('spatial_relations'):
                steps.append(_step('Связь с рабочим местом',
                                   'Рамка предмета пересекается с проекцией кандидата кассира возле стола; удержание рукой этим не доказано.' if 'cashier_near_table' in context['spatial_relations'] else
                                   'Рамка предмета устойчиво находится в проекции стола; физический контакт с поверхностью этим не доказан.', 'observation'))
            steps.append(_step('Почему выделен эпизод', 'По правилу пользователя еда и напитки у рабочего места запрещены независимо от наличия денег и ухода клиента. Это отдельная проверка присутствия предмета.', 'rule'))
        limitation = 'Не установлены приём пищи или питьё, содержимое чашки и личная принадлежность предмета. Шоколадка не должна использоваться как доказательство наличия денег.'

    elif key == 'safe_closed':
        rows = _evidence(event, {'safe'})
        departure = context.get('cashier_departure')
        departure = departure if isinstance(departure, dict) else {}
        exit_sec = departure.get('exit_sec', departure.get('start_sec'))
        if rows and _number(exit_sec) and exit_sec <= rows[0]['timestamp_sec']:
            steps.append(_step('Возможный уход кассира', 'Позиционная траектория кассира перестала наблюдаться в контролируемой зоне.', timestamp=exit_sec))
            steps.append(_step('Сейф после ухода', 'Дверца сейфа распознана открытой.', evidence=rows[0]))
            if rows[-1]['timestamp_sec'] > rows[0]['timestamp_sec']:
                steps.append(_step('Открытое состояние сохраняется', 'В последнем кадре проверенного интервала дверца по-прежнему открыта.', evidence=rows[-1]))
            steps.append(_step('Почему выделен эпизод', 'Нужно проверить открытый сейф после возможного ухода кассира и наличие ответственного сотрудника.', 'rule'))
        limitation = 'Не установлены получение денег, окончание доступа, фактический присмотр и состояние замка. Закрытая дверца не означает запертый сейф.'

    elif key == 'change_through_counter' and context.get('counter_observed_throughout_chain') is True:
        rows = _evidence(event, CASH_LABELS)
        if rows:
            steps = [_step('Банкноты со стороны кассира', 'Начальная рамка предполагаемых банкнот находится в проекции кандидата кассира.', evidence=rows[0])]
            if rows[-1]['timestamp_sec'] > rows[0]['timestamp_sec']:
                steps.append(_step('Перемещение к посетителю', 'Конечная рамка того же кандидата банкнот находится в проекции посетителя.', evidence=rows[-1]))
            if context.get('counter_approach_observed_in_chain') is False:
                steps.append(_step('Сопоставление со счётчиком', 'Счётчик виден на протяжении цепочки, но сближение рамки банкнот с ним в этой цепочке не наблюдалось.', 'rule'))
        limitation = 'Не установлены передача из руки в руку, смысл операции (возврат или выдача) и пересчёт до начала цепочки. Присутствие счётчика не доказывает его работу.'

    if not steps:
        steps = _generic_observations(event, evidence)
        if event.get('description'):
            steps.append(_step('Основание для просмотра', event['description'], 'rule'))
    if limitation is None:
        limits = event.get('limitations', [])
        limitation = ' '.join(str(value) for value in limits[:2]) or 'Эпизод требует проверки человеком; найденные визуальные признаки не устанавливают нарушение автоматически.'
    steps.append(_step('Что нужно подтвердить', limitation, 'limitation'))
    for index, step in enumerate(steps, 1):
        step['number'] = index
    return steps


